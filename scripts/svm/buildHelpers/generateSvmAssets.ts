import { readFileSync, mkdirSync, rmSync, writeFileSync } from "fs";
import { readProductionIdls } from "./productionIdls";

const idls = readProductionIdls("target/idl");
// Read everything before replacing assets, so missing/invalid inputs fail without a partial copy.
const types = new Map([...idls.keys()].map((name) => [name, readFileSync(`target/types/${name}.ts`, "utf8")]));
const assets = "src/svm/assets";
rmSync(assets, { recursive: true, force: true });
mkdirSync(`${assets}/idl`, { recursive: true });
const header = "// This file has been autogenerated. Do not edit manually.\n\n";
let idlIndex = header;
let typeIndex = header + 'export * from "./idl";\n';
for (const [name, contents] of idls) {
  const type = name
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  writeFileSync(`${assets}/idl/${name}.json`, contents);
  writeFileSync(`${assets}/${name}.ts`, types.get(name)!);
  idlIndex += `export const ${type}Idl = require("./${name}.json");\n`;
  typeIndex += `export { ${type} as ${type}Anchor } from "./${name}";\n`;
}
writeFileSync(`${assets}/idl/index.ts`, idlIndex);
writeFileSync(`${assets}/index.ts`, typeIndex);
